#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
const contract = read("src/final-response-contract.json");
const fixture = read("scripts/evaluation-fixtures-fresh-v3.json");
const manifest = read("evaluation/fixture-manifest.json");
const fixtureBytes = fs.readFileSync(path.join(root, "scripts/evaluation-fixtures-fresh-v3.json"), "utf8").replaceAll("\r\n", "\n");
const failures = [];
const fail = (message) => { failures.push(message); process.stderr.write(`FAIL: ${message}\n`); };
const terms = ["warnings", "confirmations", "uncertainty", "negation", "scope", "exact values", "ordered steps", "unfinished work", "code", "commands", "paths", "filenames", "quotations", "logs", "commits", "PR text", "docs", "files", "persisted artifacts", "delegation requests", "child responses"];
if (crypto.createHash("sha256").update(fixtureBytes).digest("hex") !== manifest.fixtureSets["fresh-v3"].sha256) fail("fresh-v3 fixture hash mismatch");
if (fixture.fixtureSet !== "fresh-v3") fail("development check must use fresh-v3 only");
if (crypto.createHash("sha256").update(contract.text).digest("hex") !== contract.sha256) fail("v11 SHA-256 mismatch");
if (contract.text.length !== contract.characters) fail("v11 character count mismatch");
for (const term of terms) if (!contract.text.toLowerCase().includes(term.toLowerCase())) fail(`v11 omits ${term}`);
const direct = fixture.categories.filter((category) => category.nested !== true);
const nested = fixture.categories.filter((category) => category.nested === true);
if (direct.length === 0 || nested.length === 0) fail("fresh-v3 needs direct and nested categories");
if (!fixture.modes.includes("off")) fail("off arm missing");
const protectedKeys = ["requiredClaims", "negatedClaims", "warnings", "commands", "paths", "identifiers", "numbers", "orderedActions", "knownGaps"];
for (const key of protectedKeys) if (!fixture.categories.some((category) => (category.requirements ?? []).some((requirement) => requirement.kind === "protected-facts" && requirement[key]?.length))) fail(`fresh-v3 lacks protected class ${key}`);
if (nested.some((category) => !category.prompt.toLowerCase().includes("child"))) fail("nested handoff is not normal");
const finalizerNodes = [{ candidate: contract.text }];
if (finalizerNodes.filter((node) => node.candidate.length > 0).length !== 1) fail("expected one finalizer injection");
process.stdout.write("selective-final v11 development check\n");
process.stdout.write(`fixture hash verified: ${manifest.fixtureSets["fresh-v3"].sha256}\n`);
process.stdout.write(`fresh-v3 categories: ${fixture.categories.length} (${direct.length} direct, ${nested.length} nested)\n`);
process.stdout.write(`protected classes: ${protectedKeys.length}\n`);
process.stdout.write("off: 0 bytes; child mode: off; handoff: normal; finalizer injections: 1\n");
process.stdout.write(`v11: ${contract.characters} characters; sha256 ${contract.sha256}\n`);
if (failures.length) { process.stderr.write(`${failures.length} v11 development check(s) failed.\n`); process.exitCode = 1; } else process.stdout.write("all selective-final v11 development checks passed\n");
